const STEP_MAP = new Map(ACHIEVEMENT_STEPS);

export function getClaimableAchievementIds(achievement = {}) {
  const claimable = [];

  for (const [rawType, rawState] of Object.entries(achievement || {})) {
    const type = Number(rawType);
    const steps = STEP_MAP.get(type);
    if (!steps || !rawState) continue;

    const completeValue = Number(rawState.completeValue) || 0;
    const lastClaimId = Number(rawState.lastClaimId) || 0;
    let startIndex = 0;
    if (lastClaimId > 0) {
      const lastIndex = steps.findIndex(([id]) => id === lastClaimId);
      if (lastIndex < 0) continue;
      startIndex = lastIndex + 1;
    }

    for (let index = startIndex; index < steps.length; index += 1) {
      const [id, requiredValue] = steps[index];
      const completed = type === 14
        ? completeValue > 0 && completeValue <= requiredValue
        : completeValue >= requiredValue;
      if (!completed) break;
      claimable.push(id);
    }
  }

  return claimable;
}
